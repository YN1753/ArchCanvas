package dialect

import (
	"fmt"
	"strings"
)

func init() {
	Register(Spec{
		ID:               "postgres",
		Aliases:          []string{"postgresql", "pg"},
		DisplayName:      "PostgreSQL",
		GormDriverImport: "gorm.io/driver/postgres",
		GormDriverModule: "gorm.io/driver/postgres v1.5.11",
		OpenExpr: func(dsnExpr string) string {
			return fmt.Sprintf("postgres.Open(%s)", dsnExpr)
		},
		DefaultDSN: func(dbName string) string {
			return fmt.Sprintf("host=localhost user=postgres password=postgres dbname=%s port=5432 sslmode=disable TimeZone=Asia/Shanghai", dbName)
		},
		PrimaryKeySQL:        "BIGINT",
		PrimaryKeyGo:         "int64",
		ForeignKeySQL:        "BIGINT",
		ForeignKeyGo:         "int64",
		BigIntSQL:            "BIGINT",
		DateTimeSQL:          "TIMESTAMPTZ",
		BooleanSQL:           "BOOLEAN",
		DecimalSQL:           "NUMERIC(10,2)",
		JSONSQL:              "JSONB",
		StringSQL:            "VARCHAR(128)",
		PromptPrimaryKeyHint: "PostgreSQL 主键类型推荐 `BIGINT` 或 `UUID`，code_type 对应 `int64` 或 `string`。",
		ForbiddenTypePatterns: []ForbiddenTypeRule{
			{Pattern: "AUTO_INCREMENT", Suggestion: "PostgreSQL 不支持 `AUTO_INCREMENT` 语法，建议改用 `BIGSERIAL` 或 `GENERATED BY DEFAULT AS IDENTITY`。"},
			{Pattern: "TINYINT(1)", Suggestion: "PostgreSQL 不支持 `TINYINT(1)`，建议改用原生 `BOOLEAN` 类型。"},
			{Pattern: "UNSIGNED", Suggestion: "PostgreSQL 标准整型不支持 `UNSIGNED` 修饰符，建议改用 `BIGINT` 或 `INTEGER`。"},
			{Pattern: "LONGTEXT", Suggestion: "PostgreSQL 不支持 `LONGTEXT`，建议统一改用 `TEXT`。"},
			{Pattern: "DATETIME", Suggestion: "PostgreSQL 不支持 `DATETIME` 类型名，建议改用 `TIMESTAMPTZ` 或 `TIMESTAMP`。"},
		},
		NormalizeGormType: func(lower string) string {
			lower = strings.TrimSpace(strings.ReplaceAll(lower, "unsigned", ""))
			switch {
			case lower == "tinyint(1)":
				return "boolean"
			case strings.HasPrefix(lower, "tinyint"):
				return "smallint"
			case strings.HasPrefix(lower, "datetime"):
				return "timestamptz"
			case lower == "longtext" || lower == "mediumtext" || lower == "tinytext":
				return "text"
			case lower == "double":
				return "double precision"
			case strings.HasSuffix(lower, "blob"):
				return "bytea"
			default:
				return lower
			}
		},
	})
}
